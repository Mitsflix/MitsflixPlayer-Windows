// The only bridge between the page and the app. Keeps Node and Electron out of the page.
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('mitsflix', {
  fetch: (url, opts) => ipcRenderer.invoke('net:fetch', url, opts),
  cacheGet: (key) => ipcRenderer.invoke('cache:get', key),
  cacheSet: (key, data) => ipcRenderer.invoke('cache:set', key, data),
  cacheClear: (prefix) => ipcRenderer.invoke('cache:clear', prefix),
  open: (url) => ipcRenderer.invoke('app:open', url),
  info: () => ipcRenderer.invoke('app:info'),
  fullscreen: (on) => ipcRenderer.invoke('win:fullscreen', on),
  checkUpdate: () => ipcRenderer.invoke('update:check'),
  installUpdate: () => ipcRenderer.invoke('update:install'),
  downloads: () => ipcRenderer.invoke('dl:list'),
  dlAdd: (spec) => ipcRenderer.invoke('dl:add', spec),
  dlRecord: (spec) => ipcRenderer.invoke('dl:record', spec),
  dlPause: (id) => ipcRenderer.invoke('dl:pause', id),
  dlResume: (id) => ipcRenderer.invoke('dl:resume', id),
  dlRemove: (id) => ipcRenderer.invoke('dl:remove', id),
  dlStopRecording: (id) => ipcRenderer.invoke('dl:stopRecording', id),
  dlHold: (delta) => ipcRenderer.invoke('dl:hold', delta),
  dlShow: (id) => ipcRenderer.invoke('dl:show', id),
  dlOpenFolder: () => ipcRenderer.invoke('dl:openFolder'),
  dlChooseFolder: () => ipcRenderer.invoke('dl:chooseFolder'),
  onDownloads: (cb) => ipcRenderer.on('dl:update', (_e, s) => cb(s)),
  subsStatus: () => ipcRenderer.invoke('subs:status'),
  subsLogin: (user, password) => ipcRenderer.invoke('subs:login', user, password),
  subsLogout: () => ipcRenderer.invoke('subs:logout'),
  subsSearch: (q) => ipcRenderer.invoke('subs:search', q),
  subsDownload: (fileId) => ipcRenderer.invoke('subs:download', fileId),
  subsPickFile: () => ipcRenderer.invoke('subs:pickFile'),
  onUpdate: (cb) => ipcRenderer.on('update:state', (_e, s) => cb(s)),
});
